CREATE OR REPLACE PROCEDURE actualizar_categoriaprod(
    p_idcategoria integer,
    p_strdescripcion varchar(60),
    p_dtmfechamodifica timestamp,
    p_strusuariomodifico varchar(20)
)
LANGUAGE plpgsql AS $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM tblcategoria_prod WHERE idcategoria = p_idcategoria) THEN
        INSERT INTO tblcategoria_prod (strdescripcion, dtmfechamodifica, strusuariomodifico)
        VALUES (p_strdescripcion, p_dtmfechamodifica, p_strusuariomodifico);
    ELSE
        UPDATE tblcategoria_prod
           SET strdescripcion = p_strdescripcion,
               dtmfechamodifica = p_dtmfechamodifica,
               strusuariomodifico = p_strusuariomodifico
         WHERE idcategoria = p_idcategoria;
    END IF;
END;
$$;

