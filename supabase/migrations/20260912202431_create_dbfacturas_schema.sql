CREATE OR REPLACE FUNCTION spconsultafactura()
RETURNS TABLE (
    nro_factura integer,
    fecha       text,
    cliente     varchar(55),
    empleado    varchar(50),
    estado      varchar(30)
)
LANGUAGE sql AS $$
    SELECT f.idfactura,
           to_char(f.dtmfecha, 'DD/MM/YYYY'),
           c.strnombre,
           e.strnombre,
           ef.strdescripcion
      FROM tblfactura f
      JOIN tblestado_factura ef ON f.idestado = ef.idestadofactura
      JOIN tblclientes c ON f.idcliente = c.idcliente
      JOIN tblempleado e ON f.idempleado = e.idempleado;
$$;

