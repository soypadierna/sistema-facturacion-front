/*
# Migración del esquema DBFACTURAS a Supabase

## Descripción
Crea todas las tablas del esquema DBFACTURAS original (SQL Server migrado a PostgreSQL)
con sus datos iniciales, procedimientos almacenados, función de consulta de facturas,
y políticas RLS para acceso desde la aplicación web.

## Tablas nuevas
1. tblcategoria_prod - Categorías de productos
2. tblroles - Roles de empleados
3. tblestado_factura - Estados de factura
4. tblclientes - Clientes
5. tblempleado - Empleados (con FK a tblroles)
6. tblseguridad - Usuarios/contraseñas del sistema (FK a tblempleado)
7. tblproducto - Productos (FK a tblcategoria_prod)
8. tblfactura - Facturas (FK a tblclientes, tblempleado, tblestado_factura)
9. tbldetalle_factura - Detalle de factura (FK a tblfactura, tblproducto)
10. tblinformes - Informes (tabla nueva para el módulo de informes)

## Seguridad
- RLS habilitado en todas las tablas
- Políticas CRUD para anon y authenticated (la app usa auth personalizado con tblseguridad)
- Acceso completo para anon ya que el login se maneja a nivel de aplicación con tblseguridad
*/

-- =================== TABLAS ===================

CREATE TABLE IF NOT EXISTS tblcategoria_prod (
    idcategoria         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    strdescripcion      varchar(60),
    dtmfechamodifica    timestamp,
    strusuariomodifico  varchar(40)
);

CREATE TABLE IF NOT EXISTS tblroles (
    idrolempleado   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    strdescripcion  varchar(50)
);

CREATE TABLE IF NOT EXISTS tblestado_factura (
    idestadofactura  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    strdescripcion   varchar(30)
);

CREATE TABLE IF NOT EXISTS tblclientes (
    idcliente           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    strnombre           varchar(55),
    numdocumento        bigint,
    strdireccion        varchar(70),
    strtelefono         varchar(30),
    stremail            varchar(50),
    dtmfechamodifica    timestamp,
    strusuariomodifico  varchar(40)
);

CREATE TABLE IF NOT EXISTS tblempleado (
    idempleado           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    strnombre            varchar(50) NOT NULL,
    numdocumento         bigint NOT NULL,
    strdireccion         varchar(100),
    strtelefono          varchar(50),
    stremail             varchar(50),
    idrolempleado        integer REFERENCES tblroles(idrolempleado),
    dtmingreso           timestamp,
    dtmretiro            timestamp,
    strdatosadicionales  text,
    dtmfechamodifica     timestamp,
    strusuariomodifico   varchar(50)
);

CREATE TABLE IF NOT EXISTS tblseguridad (
    idseguridad          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idempleado           integer NOT NULL REFERENCES tblempleado(idempleado),
    strusuario           varchar(50),
    strclave             varchar(50),
    dtmfechamodifica     timestamp,
    strusuariomodifico   varchar(50)
);

CREATE TABLE IF NOT EXISTS tblproducto (
    idproducto           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    strnombre            varchar(70) NOT NULL,
    strcodigo            varchar(30) NOT NULL,
    numpreciocompra      double precision NOT NULL,
    numprecioventa       double precision NOT NULL,
    idcategoria          integer NOT NULL REFERENCES tblcategoria_prod(idcategoria),
    strdetalle           varchar(50),
    strfoto              varchar(50),
    numstock             integer,
    dtmfechamodifica     timestamp NOT NULL,
    strusuariomodifico   varchar(40) NOT NULL
);

CREATE TABLE IF NOT EXISTS tblfactura (
    idfactura            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dtmfecha             timestamp,
    idcliente            integer NOT NULL REFERENCES tblclientes(idcliente),
    idempleado           integer NOT NULL REFERENCES tblempleado(idempleado),
    numdescuento         double precision,
    numimpuesto          double precision,
    numvalortotal        double precision,
    idestado             integer REFERENCES tblestado_factura(idestadofactura),
    dtmfechamodifica     timestamp,
    strusuariomodifico   varchar(40)
);

CREATE TABLE IF NOT EXISTS tbldetalle_factura (
    iddetalle    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idfactura    integer NOT NULL REFERENCES tblfactura(idfactura),
    numcantidad  integer CHECK (numcantidad > 0),
    idproducto   integer NOT NULL REFERENCES tblproducto(idproducto),
    numprecio    double precision CHECK (numprecio > 0.0)
);

CREATE TABLE IF NOT EXISTS tblinformes (
    idinforme     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    strtitulo     varchar(100) NOT NULL,
    strtipo       varchar(50) NOT NULL,
    strdescripcion text,
    dtmfechainicio date,
    dtmfechafin    date,
    dtmfechacreacion timestamp DEFAULT now()
);

